function getLang() {
  try {
    var l = localStorage.getItem('nw_lang');
    return (l === 'en' || l === 'et') ? l : 'et';
  } catch (e) { return 'et'; }
}

function t(key) {
  var lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.et[key] || key;
}

function applyLang() {
  var lang = getLang();
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('.lang-switch').forEach(function (btn) {
    btn.textContent = lang.toUpperCase();
  });
}

function setLang(lang) {
  try { localStorage.setItem('nw_lang', lang); } catch (e) {}
  applyLang();
}

// Wire every language switch button: click toggles ET ↔ EN
document.querySelectorAll('.lang-switch').forEach(function (btn) {
  btn.addEventListener('click', function () {
    setLang(getLang() === 'et' ? 'en' : 'et');
  });
});

applyLang();


// ===== SHARED: Cookie notice =====
(function () {
  var banner = document.getElementById('cookieBanner');
  if (!banner) return;

  var KEY = 'nw_cookies';
  var stored = null;
  try { stored = localStorage.getItem(KEY); } catch (e) {}
  if (stored) return;

  setTimeout(function () { banner.classList.add('show'); }, 900);

  function choose(value) {
    try { localStorage.setItem(KEY, value); } catch (e) {}
    banner.classList.remove('show');
  }

  var accept = document.getElementById('cookieAccept');
  var decline = document.getElementById('cookieDecline');
  var close = document.getElementById('cookieClose');
  if (accept) accept.addEventListener('click', function () { choose('accepted'); });
  if (decline) decline.addEventListener('click', function () { choose('declined'); });
  if (close) close.addEventListener('click', function () { choose('dismissed'); });
})();


// ===== SHARED: Clock Update (24h, Estonian style) =====
function updateClock() {
  var el = document.getElementById('taskbarClock');
  if (!el) return;
  var now = new Date();
  var h = now.getHours();
  var m = now.getMinutes();
  m = m < 10 ? '0' + m : m;
  el.textContent = h + ':' + m;
}
setInterval(updateClock, 1000);
updateClock();


// ===== SHARED: Smooth Page Navigation =====
function navigateTo(url) {
  var overlay = document.getElementById('pageTransition');
  if (!overlay) {
    window.location.href = url;
    return;
  }
  overlay.classList.add('active');
  setTimeout(function () {
    window.location.href = url;
  }, 400);
}

// Fade in on page load
window.addEventListener('DOMContentLoaded', function () {
  var overlay = document.getElementById('pageTransition');
  if (overlay) {
    overlay.classList.add('active');
    requestAnimationFrame(function () {
      requestAnimationFrame(function () {
        overlay.classList.remove('active');
      });
    });
  }
});


// ===== SHARED: Start Menu =====
(function () {
  var startBtn = document.getElementById('startBtn');
  var startMenu = document.getElementById('startMenu');
  if (!startBtn || !startMenu) return;

  function setOpen(open) {
    startMenu.classList.toggle('open', open);
    startBtn.classList.toggle('open', open);
    startBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
  }

  startBtn.addEventListener('click', function (e) {
    e.stopPropagation();
    setOpen(!startMenu.classList.contains('open'));
  });

  // Close on outside click or Escape
  document.addEventListener('click', function (e) {
    if (!startMenu.classList.contains('open')) return;
    if (!startMenu.contains(e.target)) setOpen(false);
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') setOpen(false);
  });
})();


// ===== SHARED: Contact Request Form =====
// No backend — the form composes the message and opens the visitor's
// mail app with everything prefilled.
(function () {
  var CONTACT_EMAIL = 'hello@noway.com';
  var forms = document.querySelectorAll('.contact-form');

  forms.forEach(function (form) {
    form.addEventListener('submit', function (e) {
      e.preventDefault();

      var nimi  = form.querySelector('[name="nimi"]');
      var epost = form.querySelector('[name="epost"]');
      var sonum = form.querySelector('[name="sonum"]');
      var status = form.querySelector('.form-status');

      function fail(field, msg) {
        if (status) {
          status.textContent = msg;
          status.style.color = '#a40000';
          status.hidden = false;
        }
        field.focus();
      }

      if (!nimi.value.trim())  return fail(nimi, t('err.name'));
      if (!epost.value.trim() || epost.value.indexOf('@') < 1) {
        return fail(epost, t('err.email'));
      }
      if (!sonum.value.trim()) return fail(sonum, t('err.msg'));

      var subject = 'Koostöösoov — ' + nimi.value.trim();
      var body = sonum.value.trim() + '\n\n—\n' + nimi.value.trim() + '\n' + epost.value.trim();

      window.location.href = 'mailto:' + CONTACT_EMAIL +
        '?subject=' + encodeURIComponent(subject) +
        '&body=' + encodeURIComponent(body);

      if (status) {
        status.textContent = t('form.sent');
        status.style.color = '#005a00';
        status.hidden = false;
      }
    });
  });
})();


// ===== INDEX PAGE: Screen click → push-in → boot → desktop =====
(function () {
  var screenOverlay = document.getElementById('screenOverlay');
  if (!screenOverlay) return;

  var started = false;

  function powerOn() {
    if (started) return;
    started = true;

    var computerContainer = document.getElementById('computerContainer');
    var hintText          = document.getElementById('hintText');
    var bootOverlay       = document.getElementById('bootOverlay');
    var pageTransition    = document.getElementById('pageTransition');
    var screenVideo      = document.getElementById('screenVideo');
    var screenVideoClick = document.getElementById('screenVideoClick');

    // Prevent double-click
    screenOverlay.style.pointerEvents = 'none';
    if (hintText) hintText.style.opacity = '0';

    // Instantly swap: hide idle, show preloaded Trim 1
    screenVideo.style.opacity = '0';
    screenVideoClick.style.opacity = '1';

    var zoomStarted = false;

    function startZoom() {
      if (zoomStarted) return;
      zoomStarted = true;
      clearTimeout(safetyTimer);

      // Short push-in toward the screen…
      computerContainer.classList.add('zooming');

      // …the fade to black finishes the move
      setTimeout(function () {
        pageTransition.classList.add('active');
      }, 300);

      // Boot screen: logo + loader, then the desktop
      setTimeout(function () {
        computerContainer.style.display = 'none';
        pageTransition.classList.remove('active');
        bootOverlay.classList.add('active');

        var bootScreen = document.getElementById('bootScreen');
        bootScreen.style.display = 'flex';
        requestAnimationFrame(function () {
          bootScreen.classList.add('visible');
        });

        setTimeout(function () {
          navigateTo('desktop.html');
        }, 2100);
      }, 1000);
    }

    // When Trim 1 finishes — push in. Fallbacks: play() rejected
    // (autoplay blocked) or 'ended' never firing on some phones.
    var safetyTimer = setTimeout(startZoom, 6000);
    var playPromise = screenVideoClick.play();
    screenVideoClick.addEventListener('ended', startZoom);
    if (playPromise && playPromise.catch) {
      playPromise.catch(startZoom);
    }
  }

  screenOverlay.addEventListener('click', powerOn);

  // Keyboard: Enter / Space also powers on
  screenOverlay.addEventListener('keydown', function (e) {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      powerOn();
    }
  });
})();


// ===== DESKTOP PAGE: Shut Down =====
function shutDown() {
  var overlay = document.getElementById('shutdownOverlay');
  if (!overlay) {
    navigateTo('index.html');
    return;
  }

  var startMenu = document.getElementById('startMenu');
  if (startMenu) startMenu.classList.remove('open');

  // Show overlay
  overlay.style.display = 'flex';
  requestAnimationFrame(function () {
    requestAnimationFrame(function () {
      overlay.classList.add('visible');
    });
  });

  // After "shutting down" text shows — play CRT off effect
  setTimeout(function () {
    overlay.classList.add('crt-off');
    // Navigate after animation finishes
    setTimeout(function () {
      navigateTo('index.html');
    }, 750);
  }, 2800);
}

