// ===== DESKTOP PAGE: Window Manager =====
// Focus (click-to-front), drag by titlebar, minimize/close via
// titlebar buttons, restore via taskbar tabs.
(function () {
  var desktop = document.querySelector('.desktop-page');
  if (!desktop) return;

  var windows = Array.prototype.slice.call(desktop.querySelectorAll('.win-window'));
  var tabs = Array.prototype.slice.call(desktop.querySelectorAll('.task-tab[data-window]'));
  var zTop = 30;

  function tabFor(win) {
    return tabs.filter(function (t) { return t.dataset.window === win.id; })[0] || null;
  }

  function focusWindow(win) {
    zTop += 1;
    win.style.zIndex = zTop;
    windows.forEach(function (w) {
      w.classList.toggle('inactive', w !== win);
      var t = tabFor(w);
      if (t) t.classList.toggle('active', w === win && !w.classList.contains('minimized'));
    });
  }

  function minimizeWindow(win) {
    win.classList.add('minimized');
    var t = tabFor(win);
    if (t) t.classList.remove('active');
  }

  function closeWindow(win) {
    win.classList.add('minimized');
    win.dataset.closed = 'true';
    var t = tabFor(win);
    if (t) t.classList.remove('active');
  }

  function restoreWindow(win) {
    win.classList.remove('minimized');
    delete win.dataset.closed;
    focusWindow(win);
  }

  windows.forEach(function (win) {
    // Bring to front on any interaction
    win.addEventListener('pointerdown', function () {
      focusWindow(win);
    });

    // Titlebar buttons
    win.querySelectorAll('.window-controls button').forEach(function (btn) {
      var action = btn.dataset.action;
      if (!action) return;
      btn.addEventListener('click', function (e) {
        e.stopPropagation();
        if (action === 'minimize') minimizeWindow(win);
        if (action === 'close') closeWindow(win);
      });
    });

    // Drag by titlebar (desktop-size screens only)
    var bar = win.querySelector('.win-titlebar');
    if (!bar) return;
    bar.addEventListener('pointerdown', function (e) {
      if (e.target.closest('button')) return;
      if (window.innerWidth < 768) return;

      var winRect = win.getBoundingClientRect();
      var deskRect = desktop.getBoundingClientRect();
      var offX = e.clientX - winRect.left;
      var offY = e.clientY - winRect.top;

      // Switch from %-based to px-based position for dragging
      win.style.width = winRect.width + 'px';
      win.style.left = (winRect.left - deskRect.left) + 'px';
      win.style.top = (winRect.top - deskRect.top) + 'px';
      win.style.right = 'auto';
      win.style.bottom = 'auto';

      function onMove(ev) {
        var x = ev.clientX - deskRect.left - offX;
        var y = ev.clientY - deskRect.top - offY;
        // Keep the titlebar reachable inside the desktop
        x = Math.max(-winRect.width + 60, Math.min(x, deskRect.width - 60));
        y = Math.max(0, Math.min(y, deskRect.height - 60));
        win.style.left = x + 'px';
        win.style.top = y + 'px';
      }

      function onUp() {
        document.removeEventListener('pointermove', onMove);
        document.removeEventListener('pointerup', onUp);
      }

      document.addEventListener('pointermove', onMove);
      document.addEventListener('pointerup', onUp);
      e.preventDefault();
    });
  });

  // Taskbar tabs: click restores / minimizes / focuses
  tabs.forEach(function (tab) {
    tab.addEventListener('click', function () {
      var win = document.getElementById(tab.dataset.window);
      if (!win) return;
      if (win.classList.contains('minimized')) {
        restoreWindow(win);
      } else if (tab.classList.contains('active')) {
        minimizeWindow(win);
      } else {
        focusWindow(win);
      }
    });
  });
})();
